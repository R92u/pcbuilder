"""Generate the curved shell's parameter-space triangulation (requires NumPy/SciPy)."""
import math
import json
from pathlib import Path
import numpy as np
from scipy.spatial import Delaunay

# Coordinates across the lid (-1..1), and along the body (-1 nose, +1 tail).
front = [
    [(.60,-.49),(.84,-.39),(.84,-.31),(.60,-.25)],
    [(.27,-.34),(.51,-.43),(.51,-.16),(.27,-.23)],
    [(.12,-.25),(.41,-.12),(.12,-.12)],
    [(.61,-.23),(.84,-.29),(.82,-.12),(.63,-.13)],
]
mirror = lambda polygon: [(-x,y) for x,y in polygon]
rear = [
    [(-.78,.03),(-.45,.15),(-.74,.25)],
    [(-.09,.12),(-.07,.45),(-.62,.27)],
    [(.08,.12),(.71,.30),(.68,.46),(.08,.28)],
    [(-.72,.40),(-.12,.53),(-.09,.68),(-.68,.50)],
    [(.07,.36),(.72,.54),(.68,.67),(.07,.52)],
    [(-.62,.62),(-.09,.75),(-.10,.90),(-.54,.76)],
    [(.08,.59),(.65,.73),(.12,.90)],
    [(-.24,.09),(-.10,-.012),(.10,-.012),(.24,.09),(.07,.11),(0,.051),(-.07,.11)],
]
rear.append(mirror(rear[0]))
# Use a seam down the underside. Top projection follows the curvature of each ring.
top=lambda poly:[(math.acos(x)/math.pi+.5,y) for x,y in poly]
holes=[top(p) for p in front+[mirror(p) for p in front]+rear]
holes.append(top([(-.115,-.77),(.115,-.77),(.115,-.39),(-.115,-.39)]))
# Flank vents at the palm and three narrow forward slits per side.
side=[[(.51,.34),(.61,.33),(.63,.60),(.52,.62)],[(.51,.68),(.60,.68),(.55,.86),(.51,.85)]]
for v in [-.69,-.62,-.55]:side.append([(.512,v),(.585,v-.015),(.585,v+.009),(.512,v+.026)])
holes+=side+[[(2-u,v) for u,v in poly] for poly in side]
pts=[]; rims=[]
def rounded(poly):
    p=np.array(poly); out=[]
    for i,b in enumerate(p):
        a=p[i-1]; c=p[(i+1)%len(p)]; r=min(.014,np.linalg.norm(a-b)*.24,np.linalg.norm(c-b)*.24)
        enter=b+(a-b)*r/np.linalg.norm(a-b);leave=b+(c-b)*r/np.linalg.norm(c-b)
        for t in (0,.5,1):out.append((1-t)**2*enter+2*t*(1-t)*b+t*t*leave)
    dense=[]
    for a,b in zip(out,out[1:]+out[:1]):
        for t in np.arange(max(1,math.ceil(np.linalg.norm(b-a)/.032)))/max(1,math.ceil(np.linalg.norm(b-a)/.032)):dense.append(a+(b-a)*t)
    return np.array(dense)
def inside(x,y,p):
    a=p;b=np.roll(p,1,axis=0)
    return np.count_nonzero(((a[:,1]>y)!=(b[:,1]>y))&(x<(b[:,0]-a[:,0])*(y-a[:,1])/(b[:,1]-a[:,1]+1e-30)+a[:,0]))%2
polys=[rounded(p) for p in holes]
for p in polys:rims.append(list(range(len(pts),len(pts)+len(p))));pts.extend(p)
rimpts=np.array(pts)
for v in np.linspace(-1,1,31):
    for u in np.linspace(0,2,41):
        if np.min(np.linalg.norm(rimpts-[u,v],axis=1))<.025 or any(inside(u,v,p) for p in polys):continue
        pts.append((u,v))
pts=np.array(pts);tris=[]
for tri in Delaunay(pts).simplices:
    if not any(inside(*pts[tri].mean(axis=0),p) for p in polys):tris.append(tri.tolist())
edges={tuple(sorted((a,b))) for tri in tris for a,b in zip(tri,tri[1:]+tri[:1])}
assert all(tuple(sorted((a,b))) in edges for rim in rims for a,b in zip(rim,rim[1:]+rim[:1]))
data=[np.round(pts,7).tolist(),tris,rims]
Path(__file__).resolve().parents[1].joinpath('dist/mg8-topology.js').write_text('// Generated by scripts/mg8-shell.py: parameters, triangles, aperture loops.\nexport default '+json.dumps(data,separators=(',',':'))+';\n')
