import fs from 'node:fs';
import {byId,categories,catalog} from '../dist/catalog.js';
import {dateStamp} from '../dist/price-quality.js';
const records={};
for(const name of ['verification-core.json','verification-support.json']){
 const evidence=JSON.parse(fs.readFileSync(new URL('../research/'+name,import.meta.url),'utf8'));
 for(const [id,record] of Object.entries(evidence.items)){
  if(records[id]||!byId[id])throw Error('Duplicate or unknown reviewed product '+id);
  if(!dateStamp(record.checkedAt)||!record.sources?.length||!record.sources.every(u=>/^https:\/\//.test(u))||Object.keys(record.values||{}).length<3)throw Error('Incomplete evidence '+id);
  for(const [key,value] of Object.entries(record.values))if(JSON.stringify(byId[id][key])!==JSON.stringify(value))throw Error('Catalog differs from evidence: '+id+'.'+key);
  records[id]={checkedAt:record.checkedAt,sources:record.sources,values:record.values,assumptions:record.assumptions||[],limitations:record.limitations||[]};
 }
}
for(const [key] of categories)if(!catalog[key].some(p=>records[p.id]))throw Error('No reviewed products for '+key);
const output='// Generated by scripts/build-verification.mjs from reviewed evidence.\nexport const verificationRecords='+JSON.stringify(records,null,2)+';\n';
const target=new URL('../dist/verification-data.js',import.meta.url);
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==output)throw Error('Verification data is stale; run node scripts/build-verification.mjs');}
else fs.writeFileSync(target,output);
console.log(Object.keys(records).length+' products have reviewed specification evidence.');
