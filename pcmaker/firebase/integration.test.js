import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {initializeTestEnvironment} from '@firebase/rules-unit-testing';
import {getApp,deleteApp} from 'firebase/app';
import {getAuth,inMemoryPersistence,GoogleAuthProvider,signInWithCredential} from 'firebase/auth';
import {doc,writeBatch,Timestamp} from 'firebase/firestore';
import {createFirebaseGallery} from './gallery-client.js';
import {demoBuild} from '../dist/catalog.js';
import {defaultFanLayout} from '../dist/fan-layout.js';
test('Google emulator identity publishes, searches, edits and removes an AIO build through the gallery adapter',async t=>{
 const projectId='demo-pcmaker-integration';
 const env=await initializeTestEnvironment({projectId,firestore:{host:'127.0.0.1',port:8080,rules:fs.readFileSync(new URL('./firestore.rules',import.meta.url),'utf8')}});
 t.after(()=>env.cleanup());await env.clearFirestore();
 await env.withSecurityRulesDisabled(async c=>{const db=c.firestore(),batch=writeBatch(db);for(const[id,facts]of Object.entries(JSON.parse(fs.readFileSync(new URL('./catalog-facts.json',import.meta.url)))))batch.set(doc(db,'catalog',id),facts);await batch.commit();});
 const originalFetch=globalThis.fetch;
 globalThis.fetch=(url,options)=>typeof url==='string'&&url.startsWith('./prices')?Promise.resolve(new Response(fs.readFileSync(new URL('../dist/'+url.slice(2),import.meta.url)))):originalFetch(url,options);
 t.after(()=>{globalThis.fetch=originalFetch;});
 const service=await createFirebaseGallery({projectId,apiKey:'demo-key',authDomain:projectId+'.firebaseapp.com'},{emulators:true,persistence:inMemoryPersistence});
 t.after(()=>deleteApp(getApp('pcmaker-gallery')));
 const base64=value=>Buffer.from(JSON.stringify(value)).toString('base64url');
 const token=base64({alg:'none',typ:'JWT'})+'.'+base64({sub:'pcmaker-qa',iss:'https://accounts.google.com',aud:'demo-google',email:'pcmaker-qa@example.test',email_verified:true,name:'Тестовый автор',iat:Math.floor(Date.now()/1000),exp:Math.floor(Date.now()/1000)+3600})+'.';
 await signInWithCredential(getAuth(getApp('pcmaker-gallery')),GoogleAuthProvider.credential(token));
 assert.equal((await service.call('/me')).user.displayName,'Тестовый автор');
 const build={...demoBuild,cooler:'aio-le240-v2'},data={title:'Проверка СЖО',description:'Только локальный тест',build,fanLayout:defaultFanLayout(build),region:'by',lighting:{mode:'rainbow',color:'#bbccff'}};
 const {id}=await service.call('/builds','POST',data);
 const item=await service.call('/builds/'+id);assert.deepEqual(item.build,build);assert.deepEqual(item.fanLayout,data.fanLayout);assert.equal(item.price.currency,'BYN');
 assert.equal((await service.call('/builds?q=проверка&offset=0')).items[0].id,id);
 await service.call('/builds/'+id,'PUT',{...data,title:'Обновлённая СЖО'});
 assert.equal((await service.call('/builds?mine=1&offset=0')).items[0].title,'Обновлённая СЖО');
 await service.call('/builds/'+id,'DELETE');assert.equal((await service.call('/builds?offset=0')).items.length,0);
 const owner=(await service.call('/me')).user.id;
 await env.withSecurityRulesDisabled(async c=>{
  const db=c.firestore(),batch=writeBatch(db);
  for(let i=0;i<32;i++)batch.set(doc(db,'builds','browse-'+i),{...data,fanLayout:{},title:'Компьютер '+String(i).padStart(2,'0'),titleKey:'компьютер '+String(i).padStart(2,'0'),authorId:i===31?'another-author':owner,authorName:'Тестовый автор',region:i<28?'by':'ru',hidden:i===30,createdAt:Timestamp.fromMillis(1700000000000+i*1000),updatedAt:Timestamp.fromMillis(1700000000000+i*1000)});
  await batch.commit();
 });
 const first=await service.call('/builds?region=by&sort=newest&offset=0');
 assert.equal(first.items.length,24);assert.equal(first.hasMore,true);assert.equal(first.items[0].id,'browse-27');assert.ok(first.items.every(item=>item.region==='by'));
 const other=await service.call('/builds?region=ru&sort=oldest&offset=0');
 assert.deepEqual(other.items.map(item=>item.id),['browse-28','browse-29','browse-31']);
 const second=await service.call('/builds?region=by&sort=newest&offset=24');
 assert.deepEqual(second.items.map(item=>item.id),['browse-3','browse-2','browse-1','browse-0']);assert.equal(second.hasMore,false);
 assert.equal((await service.call('/builds?region=by&sort=oldest&offset=0')).items[0].id,'browse-0');
 const search=await service.call('/builds?q=компьютер&region=by&sort=newest&offset=0');assert.equal(search.items[0].id,'browse-0');
 assert.deepEqual((await service.call('/builds?q=компьютер&region=by&sort=newest&offset=24')).items.map(item=>item.id),['browse-24','browse-25','browse-26','browse-27']);
 assert.deepEqual((await service.call('/builds?mine=1&region=ru&sort=name&offset=0')).items.map(item=>item.id),['browse-28','browse-29','browse-30']);
 assert.equal((await service.call('/builds?q=несуществующая&offset=0')).items.length,0);
 await service.call('/auth/logout','POST');assert.equal((await service.call('/me')).user,null);
});
